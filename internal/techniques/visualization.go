package techniques

type VisualizationScene struct {
	ID          string
	Name        string
	Emoji       string
	Description string
	Atmosphere  string
	Steps       []VisualizationStep
}

type VisualizationStep struct {
	Number      int
	Instruction string
}

func GetVisualizationScenes() []VisualizationScene {
	return buildVisualizationScenes()
}

func buildVisualizationScenes() []VisualizationScene {
	return []VisualizationScene{
		buildMountainScene(),
		buildForestScene(),
		buildBeachScene(),
		buildGardenScene(),
		buildStarryScene(),
	}
}

