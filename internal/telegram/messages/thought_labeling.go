package messages

import "fmt"

const ThoughtLabelingIntro = `🏷️ *Маркировка мыслей*

Техника когнитивной терапии для работы с тревожными мыслями.

*Как это работает:*
1. Вы описываете тревожную мысль
2. Определяете её тип (категорию)
3. Осознание типа мысли снижает её влияние

*Почему это помогает:*
Когда мы называем мысль, мы отделяем себя от неё. Это не "я тревожусь", а "это мысль типа беспокойство".

Готовы попробовать?`

const ThoughtLabelingPrompt = `💭 *Опишите тревожную мысль*

Напишите мысль, которая вас беспокоит.

_Например: "Я боюсь, что не справлюсь с работой"_`

func ThoughtLabelingCategories(thought string) string {
	return fmt.Sprintf("💭 *Ваша мысль:*\n_%s_\n\n🏷️ *К какому типу относится эта мысль?*", thought)
}

func ThoughtLabelingCategoryInfo(emoji, name, description, example string) string {
	return fmt.Sprintf(`%s *%s*

_%s_

*Пример:* %s

---

✅ Вы успешно промаркировали мысль!

Осознание типа мысли — первый шаг к снижению её влияния. Теперь вы видите эту мысль со стороны.

Хотите промаркировать ещё одну мысль?`, emoji, name, description, example)
}

